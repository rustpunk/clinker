//! Workspace guard: every production `MemoryConsumer` is listed, classified
//! and tabled.
//!
//! The contract: every production implementation of `MemoryConsumer` in the
//! workspace appears in [`MANIFEST`] with its spill class and the row of the
//! per-operator arbitration-parameters table in
//! `docs/engine/src/memory-arbitration.md` that its `spill_priority` and
//! `can_back_pressure` follow. A new consumer fails this test until someone
//! answers the Memory budget checklist in `docs/ai/32_NODE_OBLIGATIONS.md`
//! for it: which row it takes (adding the row in the same change), and
//! whether its state spills.
//!
//! A consumer whose `try_spill` frees nothing is [`SpillClass::ChargedOnly`]
//! and names the approval that allows it. A new charged-only entry needs the
//! maintainer's recorded approval; the pre-existing ones say they pre-date
//! this contract, so they are not precedent for another.
//!
//! Registering with the arbitrator is a call a consumer makes, not something
//! the compiler enforces, so this scan is what makes a new consumer visible in
//! review rather than only in a later memory incident.
//!
//! # What this scan cannot see
//!
//! It matches text, not syntax, so the gaps are named here:
//!
//! - **An impl split across lines.** Only a line that starts at column 0 with
//!   `impl` and contains `MemoryConsumer for ` is recognized; an
//!   `impl MemoryConsumer` whose `for <Type>` sits on the next line is missed.
//! - **An impl generated by a macro.** The expansion is not in the source
//!   text.
//! - **A consumer that is never registered.** The scan proves an
//!   implementation is listed, not that any code path registers it with the
//!   arbitrator, nor that state which should be a consumer implements the
//!   trait at all.
//! - **Test-only implementations are skipped by location.** An indented impl
//!   (the usual in-file `#[cfg(test)] mod tests`), a file under
//!   `src/executor/tests/`, a file named `tests.rs`, and the `tests/` and
//!   `benches/` trees of every crate are not scanned. A test fixture placed
//!   anywhere else at column 0 reads as a production consumer and fails the
//!   test loudly rather than hiding.
//! - **Only `<workspace>/crates` is walked.** An implementation outside that
//!   tree is invisible here.

use std::collections::{BTreeMap, BTreeSet};
