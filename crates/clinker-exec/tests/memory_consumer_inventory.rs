/// Whether a consumer's state can leave memory when the arbitrator asks.
enum SpillClass {
    /// `try_spill` (or the spill request it posts) moves resident state to
    /// disk.
    Spillable,
    /// Charged to the ledger but never freed by a spill. `approval` names the
    /// recorded maintainer approval, or states that the consumer pre-dates
    /// this contract.
    ChargedOnly { approval: &'static str },
}

/// One production `MemoryConsumer` implementation.
struct ManifestEntry {
    /// The implementing type's name, as it appears after `for`.
    name: &'static str,
    class: SpillClass,
    /// The full first-cell text of the consumer's row in the per-operator
    /// arbitration-parameters table, trimmed, backticks included.
    table_row: &'static str,
}

